def esc(value: object) -> str:
    text = "" if value is None else str(value)
    if text == "nan":
        return ""
    replacements = [
        ("\\", r"\textbackslash{}"),
        ("&", r"\&"),
        ("%", r"\%"),
        ("$", r"\$"),
        ("#", r"\#"),
        ("_", r"\_"),
        ("{", r"\{"),
        ("}", r"\}"),
        ("~", r"\textasciitilde{}"),
        ("^", r"\textasciicircum{}"),
    ]
    for old, new in replacements:
        text = text.replace(old, new)
    text = text.replace("<0.001", r"$<$0.001")
    return text


def read_table(stem: str) -> pd.DataFrame:
    path = TABLES / f"{stem}.csv"
    if not path.exists():
        raise FileNotFoundError(
            f"{path} missing. Run .venv/bin/python scripts/run_core_rq_experiments.py first."
        )
    return pd.read_csv(path, dtype=str).fillna("")


def clean_regressor(name: str) -> str:
    mapping = {
        "BridgeShare": "Current vehicle share",
        "route_cost_advantage_100bp": "Route-cost advantage, per 100 bp",
        "vehicle_available": "Vehicle route available",
        "vehicle_available_share": "Vehicle-route availability",
        "vehicle_depth": "Vehicle-route depth",
        "lp_concentration_share": "LP concentration",
        "no_direct_vehicle_available_share": "No-direct, vehicle-available",
        "direct_available_share": "Direct-route availability",
        "market_factor_loo": "Market liquidity factor",
        "vehicle_factor_loo": "Vehicle liquidity factor",
        "vehicle_factor_x_stress": "Vehicle factor x stress",
        "vehicle_factor_x_post_v3": "Vehicle factor x post-V3",
        "log V3 route count": "Log V3 route count",
        "log V3 route volume": "Log V3 route volume",
    }
    return mapping.get(name, name)


@dataclass
class TableSpec:
    number: str
    caption: str
    label: str
    columns: list[str]
    widths: list[str]
    rows: list[list[object]]
    note: str
    landscape: bool = False


def table_tex(spec: TableSpec) -> str:
    align = "".join(f">{{\\raggedright\\arraybackslash}}p{{{w}}}" for w in spec.widths)
    lines: list[str] = []
    if spec.landscape:
        lines.append(r"\begin{landscape}")
    lines.extend(
        [
            r"\begin{table}[!htbp]",
            r"\centering",
            r"\small",
            r"\begin{threeparttable}",
            f"\\caption{{{esc(spec.caption)}}}",
            f"\\label{{{spec.label}}}",
            f"\\begin{{tabular}}{{{align}}}",
            r"\toprule",
            " & ".join(esc(c) for c in spec.columns) + r" \\",
            r"\midrule",
        ]
    )
    current_panel = None
    for row in spec.rows:
        panel = row[0] if row and str(row[0]).startswith("Panel ") else None
        if panel and panel != current_panel:
            if current_panel is not None:
                lines.append(r"\addlinespace")
            lines.append(f"\\multicolumn{{{len(spec.columns)}}}{{l}}{{\\textit{{{esc(panel)}}}}} \\\\")
            current_panel = panel
            continue
        lines.append(" & ".join(esc(v) for v in row) + r" \\")
    lines.extend(
        [
            r"\bottomrule",
            r"\end{tabular}",
            r"\begin{tablenotes}[flushleft]",
            r"\footnotesize",
            f"\\item \\textit{{Notes:}} {esc(spec.note)}",
            r"\end{tablenotes}",
            r"\end{threeparttable}",
            r"\end{table}",
        ]
    )
    if spec.landscape:
        lines.append(r"\end{landscape}")
    return "\n".join(lines)


